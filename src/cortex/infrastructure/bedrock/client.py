"""Amazon Bedrock client adapter placeholder and mock provider.

Strict Invariant:
Amazon Bedrock is strictly used for text generation. It never performs routing or decision evaluations.
"""

import time
from typing import Any
from cortex.core.logging import get_logger
from cortex.domain.models.generation import GenerationInput, GenerationOutcome
from cortex.domain.protocols.bedrock import BedrockClientProtocol

logger = get_logger("cortex.bedrock")


class MockBedrockClient(BedrockClientProtocol):
    """Mock Bedrock client for offline development and testing."""

    def __init__(self, default_response: str | None = None) -> None:
        self.default_response = default_response or (
            "Response generated by Amazon Bedrock based on pre-evaluated decider context."
        )
        self.invocation_count = 0
        self.last_input: GenerationInput | None = None

    async def generate(self, input_data: GenerationInput) -> GenerationOutcome:
        """Simulates Bedrock generation based on the input prompt and parameters."""
        self.invocation_count += 1
        self.last_input = input_data
        logger.info(
            "Invoking Bedrock model=%s prompt_len=%d",
            input_data.model_id,
            len(input_data.prompt),
        )

        return GenerationOutcome(
            model_id=input_data.model_id,
            content=f"{self.default_response} [Query: '{input_data.prompt[:50]}...']",
            prompt_tokens=len(input_data.prompt.split()),
            completion_tokens=len(self.default_response.split()),
            total_tokens=len(input_data.prompt.split()) + len(self.default_response.split()),
            latency_ms=120.5,
        )

    async def check_health(self) -> bool:
        """Health check returns True for mock client."""
        return True
